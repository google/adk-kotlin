package com.google.adk.kt.webserver.dev.routes

import io.ktor.server.application.call
import io.ktor.server.response.respond
import io.ktor.server.routing.Route
import io.ktor.server.routing.get

/**
 * Tells the Dev UI its usage analytics are off. The UI asks on every load and whenever its tab
 * regains focus, and this server stores no consent, so the answer is always `false`.
 */
internal fun Route.telemetryConfigRoutes() {
  get("/config/telemetry") { call.respond(mapOf("telemetry" to false)) }
}
