package com.google.adk.kt.runners

import com.google.adk.kt.agents.BaseAgent
import com.google.adk.kt.agents.LiveRequestQueue
import com.google.adk.kt.agents.ResumabilityConfig
import com.google.adk.kt.agents.RunConfig
import com.google.adk.kt.annotations.ExperimentalLiveApi
import com.google.adk.kt.artifacts.ArtifactService
import com.google.adk.kt.events.Event
import com.google.adk.kt.memory.MemoryService
import com.google.adk.kt.plugins.PluginManager
import com.google.adk.kt.sessions.SessionService
import com.google.adk.kt.types.Content
import com.google.adk.kt.workflow.Node
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow

/** The Runner interface defines the contract for running agents. */
interface Runner : AutoCloseable {
  val appName: String

  /**
   * The agent this runner runs. For a node-rooted runner this is a NodeViewAgent over the running
   * node.
   */
  val agent: BaseAgent

  /**
   * The node this runner runs, set when rooted on a node graph. The go-forward field; once [agent]
   * is removed it holds the running unit for every runner.
   */
  val node: Node?
    get() = null

  val sessionService: SessionService
  val artifactService: ArtifactService?
  val memoryService: MemoryService?
  val pluginManager: PluginManager
  val resumabilityConfig: ResumabilityConfig

  /**
   * Main entry method to run the agent in this runner asynchronously.
   *
   * Stopping early, for example with `first()`, still runs the afterRun plugin callbacks. If
   * `buffer()` or `flowOn(<dispatcher>)` runs the flow in another coroutine, stopping early cancels
   * the run instead, which skips them.
   *
   * @param userId The user ID of the session.
   * @param sessionId The session ID, fetched (or created, if the runner creates missing sessions)
   *   when collection starts.
   * @param invocationId The invocation ID of the session, set this to resume an interrupted
   *   invocation.
   * @param newMessage A new message to append to the session.
   * @param stateDelta Optional state changes to apply to the session.
   * @param runConfig The run config for the agent.
   * @return The events generated by the agent.
   * @throws com.google.adk.kt.sessions.SessionNotFoundException from the flow if the session does
   *   not exist and the runner does not create missing sessions.
   */
  fun runAsync(
    userId: String,
    sessionId: String,
    invocationId: String? = null,
    newMessage: Content? = null,
    stateDelta: Map<String, Any>? = null,
    runConfig: RunConfig? = null,
  ): Flow<Event>

  /**
   * Sync interface for local testing and convenience purpose.
   *
   * @param userId The user ID of the session.
   * @param sessionId The session ID, fetched (or created, if the runner creates missing sessions)
   *   before the run starts.
   * @param newMessage A new message to append to the session.
   * @param runConfig The run config for the agent.
   * @return The events generated by the agent.
   * @throws com.google.adk.kt.sessions.SessionNotFoundException if the session does not exist and
   *   the runner does not create missing sessions.
   */
  fun run(
    userId: String,
    sessionId: String,
    newMessage: Content,
    runConfig: RunConfig? = null,
  ): Iterator<Event>

  /**
   * Runs the root agent or node, such as a workflow, live and returns a cold [Flow] of the run's
   * [Event]s, delivering a live agent's inline audio, video, and image data to the caller without
   * storing it in the session. An agent talks over a live (bidirectional streaming) connection
   * until the caller closes [liveRequestQueue] or the model ends the session, with no
   * [RunConfig.maxLlmCalls] limit; a node starts with no input and runs until it ends. The returned
   * flow fails with [UnsupportedOperationException] for a graph task agent node or a delegating
   * task agent inside a node root, before anything connects when the root's graph holds it and
   * otherwise when it starts, for a graph agent node's transfer unless the node is single-turn, and
   * for a [Runner] that does not override this.
   *
   * @param userId The user ID of the session.
   * @param sessionId The session ID, fetched (or created, if the runner creates missing sessions)
   *   when collection starts.
   * @param liveRequestQueue The queue for content, media, and activity signals.
   * @param runConfig The run configuration, or `null` for the `RunConfig()` defaults.
   * @return The run's events.
   * @throws com.google.adk.kt.sessions.SessionNotFoundException from the flow if the session does
   *   not exist and the runner does not create missing sessions.
   * @throws IllegalStateException from the flow if another live connection is reading
   *   [liveRequestQueue].
   */
  @ExperimentalLiveApi
  fun runLive(
    userId: String,
    sessionId: String,
    liveRequestQueue: LiveRequestQueue,
    runConfig: RunConfig? = null,
  ): Flow<Event> = flow {
    throw UnsupportedOperationException(
      "${this@Runner::class.simpleName ?: "This runner"} does not support live runs"
    )
  }

  /**
   * Rewinds the session to before the specified invocation.
   *
   * Appends a synthetic user-authored event with reversing `stateDelta` and `artifactDelta` entries
   * that restore session state and artifacts to what they were at the start of
   * [rewindBeforeInvocationId]. State and artifact keys prefixed with `app:` and `user:` are
   * preserved (they outlive the rewound invocation). Mirrors Python ADK `runners.py:rewind_async`.
   *
   * The default implementation throws [NotImplementedError] for temporary backward compatibility
   * with existing [Runner] implementations; override to support session rewind.
   *
   * @param userId The user ID of the session.
   * @param sessionId The session ID of the session.
   * @param rewindBeforeInvocationId The invocation to rewind before.
   * @throws com.google.adk.kt.sessions.SessionNotFoundException if the session does not exist; a
   *   rewind never creates one.
   * @throws IllegalArgumentException if no event in the session has the given invocation id.
   */
  suspend fun rewindAsync(userId: String, sessionId: String, rewindBeforeInvocationId: String) {
    throw NotImplementedError("rewindAsync for ${this::class.simpleName} is not implemented")
  }

  /**
   * Releases resources held by this runner, such as its plugins and the toolsets its agents own.
   *
   * Being [AutoCloseable] lets callers manage a runner's lifecycle idiomatically, e.g. with
   * Kotlin's `use {}`. See [AbstractRunner.close] for the standard behavior.
   */
  override fun close()
}
